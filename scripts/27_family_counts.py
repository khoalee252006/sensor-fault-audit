"""Usable models per family and training variant in every stored shift x replicate (reply to a pre-submission
review asking whether failed fits removed models or whole families from the within-family estimand P2).
A model is usable when its ID loss, OOD loss and every fault loss are finite. Seed-stability stores (*_s1, *_s2)
are left out, as in the registered analysis. Reads only stored records; writes paper_overleaf/supp_family.tex.
usage: python scripts/27_family_counts.py"""
import collections, glob, json, math, os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
VARIANTS = ("none", "gaussian", "mixed")
MIN_FAMILY = 15                                    # registered P2 threshold (scripts/16_testbed_analyze.py)


def finite(v):
    return isinstance(v, (int, float)) and math.isfinite(v)


def counts(study):
    """{family: (min per variant, max per variant, min per shift, max per shift)}, number of stores"""
    per_var, per_shift, n = collections.defaultdict(list), collections.defaultdict(list), 0
    for path in sorted(glob.glob(f"results/{study}/*.jsonl")):
        if "_s" in os.path.basename(path)[:-len(".jsonl")].split("__")[2]:
            continue
        n += 1
        cv = collections.Counter()
        for line in open(path):
            r = json.loads(line)
            ok = finite(r["id_loss"]) and finite(r["ood_loss"]) and all(finite(v) for v in r["fault_loss"].values())
            cv[(r["family"], r["variant"])] += ok
        for fam in {f for f, _ in cv}:
            vs = [cv[(fam, v)] for v in VARIANTS]
            per_var[fam] += vs
            per_shift[fam].append(sum(vs))
    return {f: (min(per_var[f]), max(per_var[f]), min(per_shift[f]), max(per_shift[f])) for f in per_var}, n


def rng(a, b):
    return f"{a}" if a == b else f"{a}--{b}"


def main():
    c1, n1 = counts("testbed")
    c2, n2 = counts("studyC")
    lines = [r"% generated by scripts/27_family_counts.py -- do not edit", r"\begin{table}[htbp]", r"\centering\footnotesize",
             r"\caption{Usable models per model family in every stored shift and replicate}", r"\label{tab:s-family}",
             r"\begin{tabular}{lrrrr}", r"\toprule",
             r" & \multicolumn{2}{c}{\StudyOne{}} & \multicolumn{2}{c}{\StudyTwo{}} \\",
             r"family & per variant & per shift & per variant & per shift \\", r"\midrule"]
    for fam in sorted(set(c1) | set(c2)):
        a, b = c1.get(fam, (0,) * 4), c2.get(fam, (0,) * 4)
        lines.append(rf"{fam} & {rng(a[0], a[1])} & {rng(a[2], a[3])} & {rng(b[0], b[1])} & {rng(b[2], b[3])} \\")
    lines += [r"\bottomrule", r"\end{tabular}",
              r"\par\smallskip\noindent\parbox{\linewidth}{\footnotesize Minimum and maximum over the "
              rf"{n1} stores of \StudyOne{{}} and the {n2} stores of \StudyTwo{{}} (shift $\times$ replicate, without the "
              r"seed-stability stores). A model is usable when its ID loss, OOD loss and every fault loss are finite. "
              r"Per variant: models trained without augmentation, with Gaussian augmentation or with mixed fault "
              rf"augmentation. The within-family estimand requires at least {MIN_FAMILY} models per family, so no family "
              r"is dropped, neither over all variants nor in the analyses without augmentation.}", r"\end{table}"]
    open("paper_overleaf/supp_family.tex", "w", encoding="utf-8").write("\n".join(lines) + "\n")
    lo = min(min(v[0] for v in c.values()) for c in (c1, c2))
    print(f"stores: {n1} + {n2}; families: {len(c1)}, {len(c2)}; smallest count per family and variant: {lo}")


if __name__ == "__main__":
    main()
