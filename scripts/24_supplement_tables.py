"""Tables of the supplementary material (paper_overleaf/supp_tables.tex), read from the result summaries.
Same house style as the paper tables (scripts/21_paper_numbers.py): title above, note below, two decimals for
correlations. usage: python scripts/24_supplement_tables.py"""
import json, os
import numpy as np

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
B = json.load(open("results/testbed/summary.json"))
C = json.load(open("results/studyC/summary.json"))
TYPE = {"temporal_drift": "time", "site_population": "site / population", "operating_condition": "operating condition",
        "recorded_faults": "recorded faults"}
GROUP = {"purpleair_ca_north": "California north", "purpleair_ca_south": "California south",
         "purpleair_west_other": "other western states", "purpleair_central_east": "central and east"}
tt = lambda s: r"\texttt{" + {"uav_power_v1": "uav_power"}.get(s, s).replace("_", r"\_") + "}"
r2 = lambda v: f"{v:+.2f}"
ci = lambda p: rf"${r2(p['est'])}$ [${r2(p['lo'])}$, ${r2(p['hi'])}$]"
short = lambda v: v.replace(" (positive)", "")


def table(label, title, spec, head, body, note, long=False):
    if long:
        return "\n".join([r"{\small", rf"\begin{{longtable}}{{{spec}}}", rf"\caption{{{title}}}\label{{{label}}}\\",
                          r"\toprule", head + r" \\", r"\midrule", r"\endfirsthead", r"\toprule", head + r" \\",
                          r"\midrule", r"\endhead", r"\bottomrule", r"\endfoot"] + body +
                         [r"\end{longtable}}", r"\tablenote{" + note + "}", ""])
    return "\n".join([r"\begin{table}[tbp]", r"\centering\small", rf"\caption{{{title}}}", rf"\label{{{label}}}",
                      rf"\begin{{tabular}}{{{spec}}}", r"\toprule", head + r" \\", r"\midrule"] + body +
                     [r"\bottomrule", r"\end{tabular}", r"\tablenote{" + note + "}", r"\end{table}", ""])


out = ["% generated by scripts/24_supplement_tables.py -- do not edit", ""]
os.makedirs("paper_overleaf", exist_ok=True)

# S1 frozen files
studyB = {"docs/PREREG_TESTBED.md", "trust/testbed.py", "scripts/16_testbed_analyze.py"}
if os.path.exists("docs/SHA256SUMS.txt"):          # code release: one file with all ten hashes
    H = {f.lstrip("*"): h for h, f in (l.split() for l in open("docs/SHA256SUMS.txt") if l.strip())}
else:                                              # working repository: Study C list + README table for Study B
    H = {f.lstrip("*"): h for h, f in (l.split() for l in open("docs/osf_upload_studyC/SHA256SUMS.txt") if l.strip())}
    readme = open("README.md", encoding="utf-8").read()
    H.update({f: readme.split(f"`{f}` | `")[1][:64] for f in studyB})
rows = []
for f in sorted(H, key=lambda f: (f not in studyB, f)):
    st = r"\StudyOne{}" if f in studyB else r"\StudyTwo{}"
    rows.append(rf"{st} & \texttt{{{f.replace('_', chr(92) + '_')}}} & \texttt{{{H[f][:16]}}}\ldots \\")
out.append(table("tab:s-hashes", "Frozen files and their registered SHA-256 hashes", "lll",
                 "study & file & SHA-256, first 16 digits", rows,
                 r"Check with \texttt{sha256sum -c docs/SHA256SUMS.txt} in the code repository. The \StudyTwo{} "
                 r"hashes are also listed in its registration; \StudyOne{} shares the runner "
                 r"\texttt{scripts/15\_testbed.py} and the data code with \StudyTwo{}."))

open("paper_overleaf/supp_hashes.tex", "w", encoding="utf-8").write("\n".join(out))
out = ["% generated by scripts/24_supplement_tables.py -- do not edit", ""]

# S2 per-domain verdicts
m1, m2 = B["P1_all_models"]["meta"]["per_domain"], B["P2_within_family"]["meta"]["per_domain"]
rows = [rf"{tt(g)} & {ci(m1[g])} & {short(m1[g]['verdict'])} & {ci(m2[g])} & {short(m2[g]['verdict'])} \\"
        for g in sorted(m1, key=lambda g: -m1[g]["est"])]
out.append(table("tab:s-domains", r"\StudyOne{}: confirmatory estimands per sensor domain", "lllll",
                 r"domain & P1, all models & verdict & P2, within families & verdict", rows,
                 r"Partial Spearman correlation between the registered robustness axis and the log OOD loss given the "
                 r"log ID loss, pooled over the shifts of each domain, with 95\,\% intervals. Fig.~2 of the paper shows "
                 r"the same values."))

# S3 every shift of Study 1
rows = []
for s in sorted(B["shifts"], key=lambda s: (s["stratum"] != "sensor", s["dataset"], s["shift"])):
    rows.append(rf"{tt(s['dataset'])} & \texttt{{{s['shift'].replace('_', chr(92) + '_')}}} & {TYPE[s['type']]} & "
                rf"{s['stratum']} & ${r2(s['line_r'])}$ & ${r2(s['rho']['v2_axis'])}$ & "
                rf"${r2(s['within']['v2_axis'])}$ & ${r2(s['rho']['disagree_ratio'])}$ \\")
out.append(table("tab:s-shifts", r"\StudyOne{}: every shift", "lllllrrr",
                 r"dataset & shift & type & stratum & $r$ & $\rho$ & $\rho_{\mathrm{fam}}$ & $\rho_{\mathrm{dis}}$",
                 rows,
                 r"$r$: Pearson correlation between log ID and log OOD loss over the 600 models. $\rho$: partial "
                 r"Spearman correlation of the registered robustness axis with the log OOD loss given the log ID loss; "
                 r"$\rho_{\mathrm{fam}}$: the same within model families; $\rho_{\mathrm{dis}}$: the same for the "
                 r"label-free disagreement ratio. Each value is the Fisher-$z$ mean over the replicates.", long=True))

# S4 Study 2 per group
rows = []
for g in GROUP:
    ps = {p["shift"]: p for p in C["per_shift"] if p["dataset"] == g}
    rows.append(rf"{GROUP[g]} & ${r2(ps['temporal_clean']['line_r'])}$ & ${r2(ps['real_faults']['line_r'])}$ & "
                rf"${r2(ps['temporal_clean']['rho']['v2_axis'])}$ & ${r2(ps['real_faults']['rho']['v2_axis'])}$ & "
                rf"${r2(C['H2']['per_group'][g])}$ & ${r2(ps['real_faults']['within_v2'])}$ \\")
out.append(table("tab:s-groups", r"\StudyTwo{}: every geographic group", "lrrrrrr",
                 r"group & $r$ clean & $r$ faults & $\rho$ clean & $\rho$ faults & $\Delta$ & $\rho_{\mathrm{fam}}$ faults",
                 rows,
                 r"$r$: Pearson correlation between log ID and log OOD loss. $\rho$: partial Spearman correlation of "
                 r"the registered robustness axis with the log OOD loss given the log ID loss, Fisher-$z$ mean over "
                 r"three replicates. $\Delta$: the H2 contrast in Fisher-$z$ units. $\rho_{\mathrm{fam}}$: within model "
                 r"families."))

open("paper_overleaf/supp_tables.tex", "w", encoding="utf-8").write("\n".join(out))
print("paper_overleaf/supp_tables.tex:", len(B["shifts"]), "shifts,", len(GROUP), "groups")
